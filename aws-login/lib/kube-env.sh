#!/bin/sh
# Shared kube/AWS environment helpers for nexus-deployer scripts.
#
# Source after SCRIPT_DIR is known:
#   . "${SCRIPT_DIR}/lib/kube-env.sh"
#   nexus_kube_env_init "${SCRIPT_DIR}"
#
# Or from kube-operator:
#   . "${SCRIPT_DIR}/lib/init-kube-env.sh"

NEXUS_AWS_LOGIN_DIR=""

# Initialize KUBECONFIG and load .active-env if present.
# Arg: aws-login directory (absolute path).
nexus_kube_env_init() {
    NEXUS_AWS_LOGIN_DIR="$1"
    if [ -z "$NEXUS_AWS_LOGIN_DIR" ]; then
        echo "nexus_kube_env_init: aws-login directory required" >&2
        return 1
    fi

    if [ -f "${NEXUS_AWS_LOGIN_DIR}/.active-env" ]; then
        # shellcheck disable=SC1090
        . "${NEXUS_AWS_LOGIN_DIR}/.active-env"
    fi

    if [ -z "${KUBECONFIG:-}" ]; then
        KUBECONFIG="${NEXUS_AWS_LOGIN_DIR}/.kube/config"
    fi
    export KUBECONFIG
    mkdir -p "$(dirname "$KUBECONFIG")"
}

# Clear credential env vars so the CLI uses the named profile only.
# Without this, a prior keys-based login can leak AKIA* into the shell and
# override --profile (seen when switching from survhana -> external-access).
nexus_aws_clear_env_credentials() {
    unset AWS_ACCESS_KEY_ID AWS_SECRET_ACCESS_KEY AWS_SESSION_TOKEN \
          AWS_DEFAULT_PROFILE 2>/dev/null || true
}

# Write .active-env for sourcing in new shells / Cursor terminals.
# Args: aws-login dir  index  label  aws_profile  region  cluster  namespace  context_alias  [auth_type]
nexus_write_active_env() {
    _dir="$1"
    _index="$2"
    _label="$3"
    _profile="$4"
    _region="$5"
    _cluster="$6"
    _namespace="$7"
    _ctx="$8"
    _auth="${9:-adfs}"

    cat > "${_dir}/.active-env" <<EOF
# Generated by set-context.sh — source this file:  . ${_dir}/.active-env
export AWS_PROFILE=${_profile}
export AWS_REGION=${_region}
export KUBECONFIG=${_dir}/.kube/config
export NEXUS_ENV_INDEX=${_index}
export NEXUS_ENV_LABEL="${_label}"
export NEXUS_AWS_AUTH_TYPE=${_auth}
export NEXUS_EKS_CLUSTER=${_cluster}
export NEXUS_K8S_NAMESPACE=${_namespace}
export NEXUS_K8S_CONTEXT=${_ctx}
export CLUSTER_NAME=${_cluster}
export REGION=${_region}
EOF
}

# Merge EKS cluster credentials into the project-local kubeconfig.
# Args: cluster_name  region  aws_profile  [context_alias]
nexus_eks_update_kubeconfig() {
    _cluster="$1"
    _region="$2"
    _profile="$3"
    _alias="${4:-}"

    if [ -z "$NEXUS_AWS_LOGIN_DIR" ]; then
        echo "nexus_eks_update_kubeconfig: call nexus_kube_env_init first" >&2
        return 1
    fi

    nexus_kube_env_init "$NEXUS_AWS_LOGIN_DIR"

    if [ -n "$_alias" ]; then
        aws eks update-kubeconfig \
            --name "$_cluster" \
            --region "$_region" \
            --profile "$_profile" \
            --alias "$_alias" \
            --kubeconfig "$KUBECONFIG"
    else
        aws eks update-kubeconfig \
            --name "$_cluster" \
            --region "$_region" \
            --profile "$_profile" \
            --kubeconfig "$KUBECONFIG"
    fi
}

# Switch kubectl context (and optional namespace) in the local kubeconfig.
# Args: context_name  [namespace]
nexus_kubectl_use_context() {
    _ctx="$1"
    _ns="${2:-}"

    kubectl config use-context "$_ctx" --kubeconfig="$KUBECONFIG"
    if [ -n "$_ns" ]; then
        kubectl config set-context "$_ctx" --namespace="$_ns" --kubeconfig="$KUBECONFIG"
    fi
}

# Print current kube/AWS context summary.
nexus_kube_env_status() {
    if [ -z "$NEXUS_AWS_LOGIN_DIR" ]; then
        echo "kube-env: not initialized" >&2
        return 1
    fi
    echo "KUBECONFIG:     ${KUBECONFIG:-unset}"
    echo "AWS_PROFILE:    ${AWS_PROFILE:-unset}"
    echo "AWS_REGION:     ${AWS_REGION:-unset}"
    if [ -f "${NEXUS_AWS_LOGIN_DIR}/.active-env" ]; then
        # shellcheck disable=SC1090
        . "${NEXUS_AWS_LOGIN_DIR}/.active-env"
        echo "Active env:     [${NEXUS_ENV_INDEX:-?}] ${NEXUS_ENV_LABEL:-?}"
        echo "Cluster:        ${NEXUS_EKS_CLUSTER:-?}"
        echo "Namespace:      ${NEXUS_K8S_NAMESPACE:-?}"
        echo "Context:        ${NEXUS_K8S_CONTEXT:-?}"
    fi
    if command -v kubectl >/dev/null 2>&1 && [ -n "${KUBECONFIG:-}" ]; then
        echo "current-context: $(kubectl config current-context --kubeconfig="$KUBECONFIG" 2>/dev/null || echo '?')"
    fi
}
